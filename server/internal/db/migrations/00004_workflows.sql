-- The automation engine: workflow definitions, versioned, and their
-- executions with per-step durability (PRD 9). Runs are checkpointed per
-- step so a crashed worker resumes instead of losing work (ADR-0004).

CREATE TABLE workflows (
    id              UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    workspace_id    UUID        NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    name            TEXT        NOT NULL,
    -- draft: editable, never executed. ready: validated and executable.
    -- archived: kept for history, no longer runs.
    status          TEXT        NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'ready', 'archived')),
    current_version INT         NOT NULL DEFAULT 1,
    created_by      UUID        REFERENCES users(id) ON DELETE SET NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX workflows_workspace_idx ON workflows (workspace_id, updated_at DESC);

CREATE TABLE workflow_versions (
    workflow_id UUID        NOT NULL REFERENCES workflows(id) ON DELETE CASCADE,
    version     INT         NOT NULL,
    definition  JSONB       NOT NULL,
    validated_at TIMESTAMPTZ,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (workflow_id, version)
);

CREATE TABLE workflow_runs (
    id              UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    workflow_id     UUID        NOT NULL REFERENCES workflows(id) ON DELETE CASCADE,
    workspace_id    UUID        NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    version         INT         NOT NULL,
    status          TEXT        NOT NULL DEFAULT 'queued'
                                CHECK (status IN ('queued', 'running', 'completed', 'failed', 'cancelled')),
    trigger_type    TEXT        NOT NULL,
    trigger_payload JSONB       NOT NULL DEFAULT '{}',
    error           TEXT        NOT NULL DEFAULT '',
    started_at      TIMESTAMPTZ,
    finished_at     TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX workflow_runs_workflow_idx ON workflow_runs (workflow_id, created_at DESC);
CREATE INDEX workflow_runs_status_idx    ON workflow_runs (status, created_at);

CREATE TABLE workflow_steps (
    run_id      UUID        NOT NULL REFERENCES workflow_runs(id) ON DELETE CASCADE,
    seq         INT         NOT NULL,
    node_id     TEXT        NOT NULL,
    node_type   TEXT        NOT NULL,
    status      TEXT        NOT NULL DEFAULT 'pending'
                            CHECK (status IN ('pending', 'running', 'completed', 'failed', 'skipped')),
    input       JSONB       NOT NULL DEFAULT '{}',
    output      JSONB       NOT NULL DEFAULT '{}',
    error       TEXT        NOT NULL DEFAULT '',
    started_at  TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    PRIMARY KEY (run_id, seq)
);

CREATE INDEX workflow_steps_run_idx ON workflow_steps (run_id, seq);

-- Monotonic sequence on events so the engine can relay them with a
-- resumable cursor (PRD 8.6 outbox consumption).
ALTER TABLE events ADD COLUMN seq BIGINT GENERATED BY DEFAULT AS IDENTITY;
CREATE INDEX events_seq_idx ON events (seq);

-- Single-row cursor tracking how far the automation engine has consumed
-- the event log.
CREATE TABLE automation_cursor (
    id             INT  PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    last_event_seq BIGINT NOT NULL DEFAULT 0,
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

